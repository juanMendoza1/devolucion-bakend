BEGIN;

-- 1. Auditoría: acción y lote/periodo afectado
ALTER TABLE auditoria_asignacion ADD COLUMN IF NOT EXISTS accion  varchar(20);
ALTER TABLE auditoria_asignacion ADD COLUMN IF NOT EXISTS job_id  varchar(255);
ALTER TABLE auditoria_asignacion ADD COLUMN IF NOT EXISTS mes     integer;
ALTER TABLE auditoria_asignacion ADD COLUMN IF NOT EXISTS anio    integer;
UPDATE auditoria_asignacion SET accion = 'ASIGNAR' WHERE accion IS NULL;

-- 2. Vínculo tarifa-aprovechador con fecha/usuario de asignación y de retiro
CREATE TABLE IF NOT EXISTS tarifa_aprovechador (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarifa_id               bigint       NOT NULL REFERENCES devol_tarifas(id),
    aprovechador_id         bigint       NOT NULL REFERENCES aprovechadores(id),
    fecha_asignacion        timestamp(6) NOT NULL,
    usuario_asignacion      varchar(100),
    activo                  boolean      NOT NULL DEFAULT true,
    fecha_retiro            timestamp(6),
    usuario_retiro          varchar(100),
    auditoria_asignacion_id bigint
);
CREATE INDEX IF NOT EXISTS idx_tarifa_aprov_tarifa       ON tarifa_aprovechador (tarifa_id);
CREATE INDEX IF NOT EXISTS idx_tarifa_aprov_aprovechador ON tarifa_aprovechador (aprovechador_id);
-- Un mismo par tarifa-aprovechador solo puede tener un vínculo ACTIVO
CREATE UNIQUE INDEX IF NOT EXISTS uk_tarifa_aprov_activo ON tarifa_aprovechador (tarifa_id, aprovechador_id) WHERE activo;

-- 3. Migrar los vínculos existentes de la tabla puente antigua.
--    La tabla vieja no guardaba fecha: se toma el último evento de auditoría de ese aprovechador
--    anterior o igual a hoy (aproximado) o, si no hay, la fecha de creación de la versión del lote.
DO $$
BEGIN
  IF to_regclass('public.devol_tarifas_aprovechadores') IS NOT NULL THEN
    INSERT INTO tarifa_aprovechador (tarifa_id, aprovechador_id, fecha_asignacion, usuario_asignacion, activo)
    SELECT dta.tarifa_id,
           dta.aprovechador_id,
           COALESCE(
             (SELECT MAX(a.fecha_asignacion) FROM auditoria_asignacion a WHERE a.aprovechador_id = dta.aprovechador_id),
             v.fecha_creacion,
             now()),
           COALESCE(
             (SELECT a.usuario_email FROM auditoria_asignacion a WHERE a.aprovechador_id = dta.aprovechador_id
              ORDER BY a.fecha_asignacion DESC LIMIT 1),
             'MIGRACION'),
           true
    FROM devol_tarifas_aprovechadores dta
    JOIN devol_tarifas t ON t.id = dta.tarifa_id
    LEFT JOIN versiones_tarifas v ON v.job_id = t.job_id
    WHERE NOT EXISTS (SELECT 1 FROM tarifa_aprovechador ta
                      WHERE ta.tarifa_id = dta.tarifa_id AND ta.aprovechador_id = dta.aprovechador_id AND ta.activo);

    -- Se conserva como respaldo, sin FKs (para que no bloquee el reset de fábrica)
    ALTER TABLE devol_tarifas_aprovechadores RENAME TO devol_tarifas_aprovechadores_old;
    ALTER TABLE devol_tarifas_aprovechadores_old DROP CONSTRAINT IF EXISTS fk2wm67v3w541qegsl42xqod5yg;
    ALTER TABLE devol_tarifas_aprovechadores_old DROP CONSTRAINT IF EXISTS fk8kqaewlvcxkbqypl2f6tvhfyy;
  END IF;
END $$;

-- 4. Columna huérfana de versiones_tarifas (no mapeada en JPA) que referencia devol_tarifas
ALTER TABLE versiones_tarifas DROP CONSTRAINT IF EXISTS fk703kkohavi8t20j4jkfm2yh4o;

COMMIT;

-- 5. Índices de rendimiento (fuera de la transacción; en tablas grandes tardan)
CREATE INDEX IF NOT EXISTS idx_reliq_maestro_job       ON reliquidaciones (devolucion_maestro_id, job_id, id);
CREATE INDEX IF NOT EXISTS idx_reliq_codigo            ON reliquidaciones (codigo_dataease);
CREATE INDEX IF NOT EXISTS idx_factura_periodo_estrato ON factura_original (ano, mes, estrato);
CREATE INDEX IF NOT EXISTS idx_devol_tarifas_job       ON devol_tarifas (job_id, mes, anio);
ANALYZE reliquidaciones;
ANALYZE factura_original;
